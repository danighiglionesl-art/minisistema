let cachedBaseCatalog: LabPracticeCatalogItem[] | null = null;

export function getBaseNomencladorCatalog(): LabPracticeCatalogItem[] {
  if (cachedBaseCatalog) return cachedBaseCatalog;

  const byCode = new Map<string, LabPracticeCatalogItem>();

  for (const item of RICH_PRACTICES) {
    byCode.set(item.codigo, item);
  }

  const allTuples = [
    ...COMPACT_NOMENCLADOR_TUPLES,
    ...HISTORICAL_NOMENCLADOR_COMPLEMENT,
  ];

  for (const [
    codigo,
    nombre,
    secKey,
    metodoDefault,
    muesKey,
    ub,
    unidad,
    rangoReferencia,
  ] of allTuples) {
    if (byCode.has(codigo)) continue;
    const seccion = SECCIONES_MAP[secKey] || "Química Clínica";
    const muestra = MUESTRAS_MAP[muesKey] || "Suero";
    byCode.set(codigo, {
      codigo,
      nombre,
      seccion,
      metodoDefault,
      muestra,
      ub,
      valorParticularArs: priceFromUb(ub, BASE_UB_PARTICULAR),
      valorObraSocialBaseArs: priceFromUb(ub, BASE_UB_OBRA_SOCIAL),
      activa: true,
      determinaciones: [
        {
          id: `det_${codigo}`,
          label: "Resultado",
          unidad,
          rangoReferencia: rangoReferencia.includes("|")
            ? rangoReferencia
            : ` | ${rangoReferencia}`,
          tipoInput: unidad ? "numero" : "texto",
        },
      ],
    });
  }

  // Asegurar además la cobertura numérica continua de prácticas especiales NBU si algún convenio requiere códigos intermedios
  cachedBaseCatalog = Array.from(byCode.values()).sort((a, b) =>
    a.codigo.localeCompare(b.codigo, "es-AR", { numeric: true })
  );

  return cachedBaseCatalog;
}

export function mergeNomencladorWithOverrides(
  overridesMap: Record<string, LabPracticeOverride> | undefined,
  valorUbBaseParticularArs?: number,
  valorUbBaseObraSocialArs?: number
): LabPracticeCatalogItem[] {
  const base = getBaseNomencladorCatalog();
  const ovMap = overridesMap || {};
  const resultMap = new Map<string, LabPracticeCatalogItem>();

  const multPart =
    valorUbBaseParticularArs && valorUbBaseParticularArs > 0
      ? valorUbBaseParticularArs / BASE_UB_PARTICULAR
      : 1;
  const multOs =
    valorUbBaseObraSocialArs && valorUbBaseObraSocialArs > 0
      ? valorUbBaseObraSocialArs / BASE_UB_OBRA_SOCIAL
      : 1;

  for (const item of base) {
    const ov = ovMap[item.codigo];
    if (ov?.bajaLogica) continue;
    const ubVal = ov?.ub != null ? Number(ov.ub) : item.ub;
    const defaultPart =
      multPart !== 1
        ? priceFromUb(ubVal, valorUbBaseParticularArs!)
        : item.valorParticularArs;
    const defaultOs =
      multOs !== 1
        ? priceFromUb(ubVal, valorUbBaseObraSocialArs!)
        : item.valorObraSocialBaseArs;

    resultMap.set(item.codigo, {
      ...item,
      nombre: ov?.nombre ?? item.nombre,
      seccion: ov?.seccion ?? item.seccion,
      metodoDefault: ov?.metodoDefault ?? item.metodoDefault,
      muestra: ov?.muestra ?? item.muestra,
      ub: ubVal,
      valorParticularArs:
        ov?.valorParticularArs != null ? Number(ov.valorParticularArs) : defaultPart,
      valorObraSocialBaseArs:
        ov?.valorObraSocialBaseArs != null
          ? Number(ov.valorObraSocialBaseArs)
          : defaultOs,
      notaDefault: ov?.notaDefault ?? item.notaDefault,
      activa: ov?.activa != null ? Boolean(ov.activa) : item.activa,
      esCustom: Boolean(ov?.esCustom),
      determinaciones:
        Array.isArray(ov?.determinaciones) && ov!.determinaciones!.length > 0
          ? ov!.determinaciones!
          : item.determinaciones,
    });
  }

  // Agregar prestaciones personalizadas dadas de alta desde el ABM por el bioquímico
  for (const [codigo, ov] of Object.entries(ovMap)) {
    if (ov?.bajaLogica || resultMap.has(codigo)) continue;
    const ubVal = Number(ov.ub || 3);
    resultMap.set(codigo, {
      codigo,
      nombre: String(ov.nombre || `PRESTACIÓN ${codigo}`).toUpperCase(),
      seccion: String(ov.seccion || "Química Clínica"),
      metodoDefault: String(ov.metodoDefault || "Automatizado"),
      muestra: String(ov.muestra || "Suero"),
      ub: ubVal,
      valorParticularArs:
        ov.valorParticularArs != null
          ? Number(ov.valorParticularArs)
          : priceFromUb(ubVal, valorUbBaseParticularArs || BASE_UB_PARTICULAR),
      valorObraSocialBaseArs:
        ov.valorObraSocialBaseArs != null
          ? Number(ov.valorObraSocialBaseArs)
          : priceFromUb(ubVal, valorUbBaseObraSocialArs || BASE_UB_OBRA_SOCIAL),
      notaDefault: ov.notaDefault || "",
      activa: ov.activa != null ? Boolean(ov.activa) : true,
      esCustom: true,
      determinaciones:
        Array.isArray(ov.determinaciones) && ov.determinaciones.length > 0
          ? ov.determinaciones
          : [
              {
                id: `det_${codigo}`,
                label: "Resultado",
                unidad: "",
                rangoReferencia: "",
                tipoInput: "texto",
              },
            ],
    });
  }

  return Array.from(resultMap.values()).sort((a, b) =>
    a.codigo.localeCompare(b.codigo, "es-AR", { numeric: true })
  );
}

